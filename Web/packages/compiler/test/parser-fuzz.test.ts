//
//  parser-fuzz.test.ts — the SEEDED, DETERMINISTIC hostile-parser fuzz gate (WD-fuzz).
//
//  Contract under test: the two source→IR entry points — parseDsx (the tokenizer/parser,
//  source → XmlNode) and compileComponent (source → the component IR) — must NEVER crash
//  the process on any input. For every case the outcome is EITHER a value (it parsed) OR a
//  throw of the parser's ONE declared structured error type, DsxParseError. Any other thrown
//  type (a RangeError from stack exhaustion, a TypeError from an unguarded access, a bare
//  Error, …) is a FAILURE, as is a single case that blows the per-case time budget (the
//  hang/OOM proxy for a bounded input). A failure prints the seed, family, index and the
//  exact input so it reproduces in one line.
//
//  This replaces a withdrawn README claim ("a 50,000-case run") with a real, committed,
//  repeatable gate. The corpus is generated by a committed mulberry32 PRNG over a FIXED seed
//  set — no Math.random (the runtime forbids it, /web/07, and a fuzz gate must reproduce
//  byte-for-byte). Same seeds ⇒ identical corpus every run. It rides `npm test` (which globs
//  packages/*/test/*.test.ts and is what the codemagic web-kernel lane runs); `npm run fuzz`
//  runs this file alone, and `DSX_FUZZ_CASES=<n> npm run fuzz` runs a larger manual campaign
//  without changing the committed corpus.
//
//  Every hostile byte in the alphabets below is written as an ASCII escape on purpose, so
//  this source file stays pure ASCII and survives grep/git/editor tooling unharmed — the
//  degenerate bytes live in the RUNTIME strings, never in the file bytes.
//

import { test } from "node:test";
import assert from "node:assert/strict";

import { parseDsx, DsxParseError } from "../src/xml.ts";
import { compileComponent } from "../src/component.ts";

// ── seeded PRNG: mulberry32 ───────────────────────────────────────────────────────────
// A 32-bit state, integer-only step + one power-of-two division; fully deterministic and
// identical across platforms (IEEE-754). Chosen over xorshift for its slightly better
// low-bit avalanche at this size.
function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return function (): number {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

class Rng {
  private nextFloat: () => number;
  constructor(seed: number) {
    this.nextFloat = mulberry32(seed);
  }
  /** the raw [0,1) draw */
  float(): number {
    return this.nextFloat();
  }
  /** integer in [0, nExclusive) */
  int(nExclusive: number): number {
    return Math.floor(this.nextFloat() * nExclusive);
  }
  /** integer in [lo, hi] inclusive */
  range(lo: number, hi: number): number {
    return lo + this.int(hi - lo + 1);
  }
  pick<T>(items: readonly T[]): T {
    return items[this.int(items.length)]!;
  }
  bool(p = 0.5): boolean {
    return this.nextFloat() < p;
  }
  /** repeat a builder 0..maxExclusive-1 times, concatenating */
  repeatStr(maxExclusive: number, build: () => string): string {
    const n = this.int(maxExclusive);
    let out = "";
    for (let i = 0; i < n; i++) out += build();
    return out;
  }
}

